const u8 *USB_GetDescriptor(u8 type, u16 *len)
{
    switch (type)
    {
    case USB_DESC_DEVICE:
        *len = 18;
        return device_desc;
    case USB_DESC_CONFIGURATION:
        *len = 34;
        return config_desc;
    case USB_DESC_REPORT:
        *len = 62;
        return report_desc;
    default:
        *len = 0;
        return NULL;
    }
}
